    fn identity(manufacturer: &str, firmware: (u16, u16)) -> TpmIdentity {
        TpmIdentity {
            manufacturer: manufacturer.into(),
            vendor: String::new(),
            firmware,
        }
    }

    #[test]
    fn firmware_advisories_follow_the_published_version_lists() {
        // ROCA, by the NSA detection script's rules.
        for weak in [
            (4, 33),
            (4, 40),
            (4, 42),
            (5, 61),
            (6, 42),
            (7, 61),
            (133, 32),
            (149, 32),
        ] {
            assert_eq!(
                identity("IFX", weak).advisory(),
                Some(FirmwareAdvisory::Roca),
                "{weak:?}"
            );
        }
        for fixed in [
            (4, 34),
            (4, 43),
            (5, 62),
            (6, 43),
            (7, 62),
            (133, 33),
            (149, 33),
            (8, 0),
        ] {
            assert_eq!(identity("IFX", fixed).advisory(), None, "{fixed:?}");
        }
        // TPM-FAIL, by NVD's exact versions; the reported 73.20 and 74.12 are not listed.
        for listed in [(71, 0), (71, 12), (73, 8), (73, 9), (74, 16)] {
            assert_eq!(
                identity("STM", listed).advisory(),
                Some(FirmwareAdvisory::TpmFail),
                "{listed:?}"
            );
        }
        for unlisted in [(73, 20), (74, 12), (71, 13)] {
            assert_eq!(identity("STM", unlisted).advisory(), None, "{unlisted:?}");
        }
        // A version is only read against its own manufacturer's list.
        assert_eq!(identity("INTC", (7, 61)).advisory(), None);
        assert_eq!(identity("AMD", (71, 12)).advisory(), None);
    }
